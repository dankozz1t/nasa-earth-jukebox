const DICTS: Record<Lang, Dict> = { en, uk };
export const KEYS = Object.keys(en);

let current: Lang = "en";

export function getLang(): Lang {
  return current;
}

const listeners = new Set<() => void>();

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  listeners.forEach((cb) => cb());
}

export function subscribe(cb: () => void): () => void {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

// Falls back to English, then to the key itself.
export function t(
  key: string,
  vars: Record<string, string | number> = {},
  lang: Lang = current,
): string {
  const template = DICTS[lang][key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}

export function layerText(
  key: string,
  lang: Lang = current,
): { label: string; voice: string; about: string } {
  return LAYER_TEXT[lang][key] ?? LAYER_TEXT.en[key] ?? { label: key, voice: "", about: "" };
}

// The sound service writes the note on a rule-based piece in English only; its Ukrainian text lives here.
// AI pieces carry their own Ukrainian note.
export function rationaleText(
  s: { mode: string; rationaleEn: string; rationaleUk: string; composer?: { used: string } },
  lang: Lang = current,
): string {
  if (lang === "en") return s.rationaleEn;
  if (s.rationaleUk) return s.rationaleUk;
  const used = s.composer?.used;
  if (used === "algorithmic") {
    const mode = t(s.mode === "minor" ? "rationale.minor" : "rationale.major", {}, lang);
    return t("rationale.rules", { mode }, lang);
  }
  if (used === "aerosol") return t("rationale.aerosol", {}, lang);
  return s.rationaleEn;
}

export function dictFor(lang: Lang): Dict {
  return DICTS[lang];
}
